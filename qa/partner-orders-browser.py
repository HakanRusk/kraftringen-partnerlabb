"""Order proposal UI, partner scoping, forms and responsive layout in CI Chromium."""
import asyncio
import os
from pathlib import Path
from playwright.async_api import async_playwright, expect
BASE = os.environ.get('PARTNERLABB_QA_URL', 'http://127.0.0.1:8000/')
OUT = Path(os.environ.get('PARTNERLABB_QA_SHOTS', '/tmp/partnerlabb-shots'))

async def main():
    OUT.mkdir(parents=True, exist_ok=True)
    async with async_playwright() as pw:
        browser = await pw.chromium.launch()
        for width in (1440, 390, 320):
            context = await browser.new_context(viewport={'width':width,'height':900})
            page = await context.new_page()
            errors=[]
            page.on('pageerror',lambda error: errors.append(str(error)))
            page.on('dialog',lambda dialog: dialog.accept())
            try:
                # Ordinary existing-partner entry: no opt-in URL or stored preference.
                await page.goto(BASE)
                await expect(page.locator('#ow-login')).to_have_count(0)
                await page.locator('#role').select_option('partner')
                await page.locator('#partner').select_option('vast')
                await expect(page.locator('#role')).to_have_value('partner')
                await expect(page.locator('#partner')).to_have_value('vast')
                await expect(page.locator('.ow-head h1')).to_have_text('Ordrar & resultat')
                await page.locator('[data-ow-filter=year]').select_option('2026')
                await page.locator('[data-ow-filter=month]').select_option('10')
                assert await page.evaluate('document.documentElement.scrollWidth <= innerWidth'), width
                await page.screenshot(path=str(OUT/f'report-orders-home-{width}.png'),full_page=True)
                await expect(page.locator('[data-ow-status]')).to_have_count(12)
                await expect(page.locator('.ow-withdrawal-branch [data-ow-status=withdrawn]')).to_have_count(1)
                for route in ('products','academy','support','overview'):
                    await page.locator(f'.ow-tabs [data-go="{route}"]').click()
                    await expect(page.locator('.ow-tabs [aria-current="page"]')).to_have_attribute('data-go',route)
                    assert await page.evaluate('document.querySelector("#view").firstElementChild.classList.contains("ow-tabs")')
                    assert await page.evaluate('document.documentElement.scrollWidth <= innerWidth'), (width,route)
                    await expect(page.locator('#partner')).to_have_value('vast')
                await page.locator('.ow-tabs [data-go="products"]').click()
                await expect(page.locator('.pc-product')).to_have_count(3)
                await page.locator('#pc-price-list').select_option('face2face-demo-v1')
                await expect(page.locator('.pc-product').filter(has=page.get_by_role('heading',name='Kraftringen Opti',exact=True))).to_contain_text('99')
                await page.get_by_role('button',name='Skapa order för Kraftringen Opti',exact=True).click()
                await expect(page.locator('#ow-order-form [name=product]')).to_have_value('Kraftringen Opti')
                await expect(page.locator('#ow-order-form [name=priceListId]')).to_have_value('face2face-demo-v1')
                await page.locator('[data-ow-cancel]').click()
                await expect(page.locator('.pc-comparison tbody tr')).to_have_count(3)
                await expect(page.locator('[data-pc-category=business]')).to_have_count(0)
                await page.locator('#role').select_option('internal')
                await page.evaluate("Portal.selectedPartnerId='vast';Portal.go('product-access')")
                await expect(page.locator('#pc-access-form')).to_be_visible()
                await page.locator('[name=audience][value=business]').check()
                for checkbox in await page.locator('[data-access-category=business] [name=product]').all():
                    await checkbox.check()
                await page.get_by_role('button',name='Spara partnerns sortiment').click()
                await expect(page.locator('#pc-access-message')).to_contain_text('Sparat')
                assert await page.evaluate('document.documentElement.scrollWidth <= innerWidth'), ('access',width)
                await page.screenshot(path=str(OUT/f'report-product-access-{width}.png'),full_page=True)
                await page.reload()
                await page.locator('#role').select_option('partner')
                await page.locator('#partner').select_option('vast')
                await page.locator('.ow-tabs [data-go="products"]').click()
                await page.locator('[data-pc-category=business]').click()
                await expect(page.locator('.pc-comparison tbody tr')).to_have_count(7)
                if width == 1440:
                    assert await page.locator('.pc-comparison').evaluate('(el)=>el.getBoundingClientRect().bottom <= innerHeight'), 'comparison fits desktop viewport'
                await page.locator('[data-pc-jump]').first.click()
                await expect(page.locator('#pc-product-3')).to_be_focused()

                await expect(page.locator('.pc-product')).to_have_count(7)
                assert await page.evaluate('document.documentElement.scrollWidth <= innerWidth'), ('products',width)
                await page.screenshot(path=str(OUT/f'report-products-{width}.png'),full_page=True)
                await page.get_by_role('button',name='Skapa order för Kraftringen Direkt',exact=True).click()
                await expect(page.locator('#ow-order-form [name=customerType]')).to_have_value('company')
                await expect(page.locator('#ow-order-form')).to_contain_text('Prisunderlag saknas')
                await page.locator('[data-ow-cancel]').click()
                await page.locator('.ow-tabs [data-go="overview"]').click()
                await expect(page.locator('.ow-flow')).to_be_visible()
                await expect(page.locator('#nav [data-go="order-list"],#nav [data-go="partner-sales"]')).to_have_count(0)
                await page.locator('[data-ow-stage=approved]').click()
                await expect(page.locator('[data-ow-filter=status]')).to_have_value('stage:approved')
                assert await page.locator('#ow-order-list tbody tr').count() >= 1
                await page.locator('[data-ow-open]').first.click()
                await expect(page.locator('.ow-status-history')).to_be_visible()
                await expect(page.locator('.ow-status-history time').first).to_be_visible()
                await page.locator('#close-dialog').click()
                await page.locator('[data-ow-status=approved]').click()
                await expect(page.locator('[data-ow-filter=status]')).to_have_value('approved')
                await expect(page.locator('#ow-order-list tbody tr')).to_have_count(1)
                await page.locator('[data-ow-filter=mode]').select_option('week')
                await page.locator('[data-ow-filter=week]').select_option('41')
                await expect(page.locator('#ow-order-list tbody')).to_contain_text('Exempelperson 3')
                await page.locator('[data-ow-filter=mode]').select_option('month')
                await page.locator('[data-ow-filter=status]').select_option('all')
                await page.locator('[data-ow-customer]').first.click()
                form=page.locator('#ow-customer-form')
                await form.locator('[name=name]').fill('Fiktiv Testkund')
                await form.locator('[name=type]').select_option('private')
                await form.locator('[name=postalAddress]').fill('Exempelgatan 4')
                await form.locator('[name=visitAddress]').fill('Exempelvägen 7')
                await form.locator('[name=email]').fill('test@kund.example')
                await form.get_by_role('button',name='Spara kund').click()
                await expect(page.locator('#view')).to_contain_text('Fiktiv Testkund')
                await page.locator('[data-ow-order]').click()
                form=page.locator('#ow-order-form')
                await form.locator('[name=customerId]').select_option(label='Fiktiv Testkund')
                assert await form.locator('[name=termMonths]').count()==0
                assert await form.locator('[data-field=network]').count()==0
                await form.locator('[name=product]').select_option('Kraftringen Opti')
                await form.locator('[name=startDate]').fill('2026-12-01')
                await form.locator('[data-field=installationId]').fill('735999999999999998')
                await form.locator('[data-field=annualKwh]').fill('12000')
                await form.locator('[data-ow-add]').click()
                assert await form.locator('[data-facility]').count()==2
                second=form.locator('[data-facility]').nth(1)
                await second.locator('[data-field=installationId]').fill('735999999999999997')
                await second.locator('[data-field=annualKwh]').fill('6000')
                for control in await form.locator('input,select').all():
                    box=await control.bounding_box()
                    assert box and box['x']>=0 and box['x']+box['width']<=width+1,(width,box)
                await form.get_by_role('button',name='Registrera order · demo').click()
                await expect(page.locator('#portal-dialog')).not_to_be_visible()
                await page.locator('[data-ow-filter=mode]').select_option('year')
                await page.locator('[data-ow-filter=year]').select_option('2026')
                await page.locator('[data-ow-search]').fill('Fiktiv Testkund')
                await page.locator('[data-ow-open]').click()
                await page.get_by_role('button',name='Godkänd · demo',exact=True).click()
                await expect(page.get_by_role('button',name='Bindande avtal · demo',exact=True)).to_have_count(0)
                await page.get_by_role('button',name='Orderbekräftelse skickad · demo',exact=True).click()
                await expect(page.locator('#dialog-title')).to_have_text('Order · Orderbekräftelse skickad')
                await expect(page.get_by_role('button',name='Ångrad · demo',exact=True)).to_be_visible()
                await page.get_by_role('button',name='Bindande avtal · demo',exact=True).click()
                await expect(page.get_by_role('button',name='Ångrad · demo',exact=True)).to_have_count(0)
                await expect(page.locator('#dialog-title')).to_have_text('Order · Bindande avtal')
                await page.get_by_role('button',name='Väntar på avtalsstart · demo',exact=True).click()
                await page.get_by_role('button',name='Aktivt avtal · demo',exact=True).click()
                await expect(page.locator('#dialog-title')).to_have_text('Order · Aktivt avtal')
                await page.locator('#close-dialog').click()
                await page.reload()
                await page.locator('[data-ow-search]').fill('Fiktiv Testkund')
                await expect(page.locator('#ow-order-list tbody')).to_contain_text('Aktivt avtal')
                await page.get_by_role('button',name='Visa provisionsstatistik →').click()
                await expect(page.locator('.ow-metrics')).to_contain_text('Berättigad provision')
                await expect(page.locator('.ow-metrics')).to_contain_text('Bindande avtal')
                await expect(page.locator('.oc-calculation')).not_to_have_attribute('open','')
                await page.locator('#oc-dataset').select_option('new')
                await page.locator('#oc-month').fill('2026-10')
                await expect(page.locator('.oc-total')).to_contain_text('4 500'.replace(' ','\u00a0'))
                await page.locator('#oc-example').click()
                await expect(page.locator('#oc-month')).to_have_value('2026-04')
                await expect(page.locator('.oc-total')).to_contain_text('7 500'.replace(' ','\u00a0'))
                await page.get_by_text('Så här har vi räknat',exact=True).click()
                await expect(page.locator('.oc-calculation')).to_have_attribute('open','')
                await expect(page.locator('.oc-calculation')).to_contain_text('ännu inte avräknat')
                assert await page.evaluate('document.documentElement.scrollWidth <= innerWidth'), width
                await page.screenshot(path=str(OUT/f'report-orders-commission-{width}.png'),full_page=True)
                await page.get_by_role('button',name='Byt demoinloggning',exact=True).click()
                await page.locator('#ow-login select').select_option('syd')
                await page.get_by_role('button',name='Öppna partnerns startsida').click()
                await expect(page.locator('#view')).not_to_contain_text('Fiktiv Testkund')
                await page.locator('[data-ow-order]').click()
                form=page.locator('#ow-order-form')
                await form.locator('[name=product]').select_option('Kraftringen Direkt')
                await form.locator('[name=termType]').select_option('fixed')
                await expect(form.locator('[name=termMonths]')).to_be_visible()
                await expect(form.locator('[data-field=network]')).to_be_visible()
                assert await form.locator('[data-month]').count()==12
                for control in await form.locator('input,select').all():
                    box=await control.bounding_box()
                    assert box and box['x']>=0 and box['x']+box['width']<=width+1,(width,box)
                await page.screenshot(path=str(OUT/f'report-orders-business-{width}.png'),full_page=True)
                await form.locator('[data-ow-cancel]').click()
                await page.locator('[data-ow-legacy]').click()
                await expect(page.locator('.partner-start-choice')).to_have_count(4)
                await page.goto(BASE+'?partner=syd#partner-sales')
                await expect(page.locator('#role')).to_have_value('internal')
                await page.get_by_role('button',name='Visa ordrar & status',exact=True).click()
                await expect(page.locator('#partner')).to_have_value('syd')
                await expect(page.locator('[data-ow-status]')).to_have_count(12)
                await expect(page.locator('.ow-withdrawal-branch [data-ow-status=withdrawn]')).to_have_count(1)
                await page.reload()
                await expect(page.locator('[data-ow-status]')).to_have_count(12)
                await expect(page.locator('.ow-withdrawal-branch [data-ow-status=withdrawn]')).to_have_count(1)
                assert not errors, errors
                print(f'PASS order proposal at {width}px: login, cohort, create, multi-site, confirm, reload, partner, profile, rollback',flush=True)
            except Exception:
                await page.screenshot(path=str(OUT/f'orders-failure-{width}.png'),full_page=True)
                raise
            finally:
                await context.close()
        await browser.close()
asyncio.run(main())
